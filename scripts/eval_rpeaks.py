#!/usr/bin/env python
"""EXPLORATORY evaluation of the prototype R-peak detector on MIT-BIH records.

For each record: detect R-peaks on channel MLII, take the annotation file beats
as reference (beat_only), and report TP/FP/FN, sensitivity and PPV.

This is an engineering check on terrestrial hospital recordings. It is not a
clinical result and says nothing about a person's health.
"""

from src.ingest.wfdb_loader import (
    beat_only,
    get_signal,
    load_beat_annotations,
    load_record,
)
from src.features.rpeaks import detect_rpeaks, match_beats
from src.config import load_params
import argparse
import sys
from collections import Counter
from pathlib import Path

import numpy as np
import wfdb
from wfdb.io.annotation import ann_label_table

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))


HEADER = (
    "EXPLORATORY. Terrestrial ambulatory data. Records 201 and 202\n"
    "are the same subject. No clinical claim. Parameters fixed before looking at "
    "results; do not tune on 201/202."
)

DEFAULT_RECORDS = ["100", "201", "202"]
DESCRIPTIONS = dict(
    zip(ann_label_table["symbol"], ann_label_table["description"]))


def evaluate(record_name, raw_dir, channel, params):
    path = str(Path(raw_dir) / record_name)
    rec = load_record(path)
    signal = get_signal(rec, channel)
    detected = detect_rpeaks(signal, rec.fs, params["rpeaks"])

    samples, symbols, _aux_notes = load_beat_annotations(path)
    n = min(rec.sig_len, len(signal))
    inside = np.array([i for i in range(len(samples))
                      if samples[i] < n], dtype=int)
    reference, beat_symbols = beat_only(
        samples[inside], [symbols[i] for i in inside])

    match = match_beats(
        detected, reference, rec.fs, params["rpeaks"]["match_tolerance_ms"]
    )
    counts = Counter(beat_symbols)
    return {
        "record": record_name,
        "channel": channel,
        "fs": rec.fs,
        "duration_s": n / float(rec.fs),
        "n_detected": int(len(detected)),
        "n_reference": int(len(reference)),
        "match": match,
        "symbols": counts,
    }


def fmt(value, digits=4):
    return "n/a" if value is None else f"{value:.{digits}f}"


def write_report(results, params, path):
    rp = params["rpeaks"]
    lines = []
    lines.append("# R-peak evaluation (prototype detector)")
    lines.append("")
    lines.append(HEADER.replace("\n", " "))
    lines.append("")
    lines.append(
        "Generated by `scripts/eval_rpeaks.py`. Detection is on channel MLII;")
    lines.append(
        "reference beats come from the MIT-BIH annotation file after `beat_only`.")
    lines.append("")
    lines.append("## Parameters used")
    lines.append("")
    lines.append("| parameter | value |")
    lines.append("|-----------|-------|")
    for key in (
        "bandpass_low_hz",
        "bandpass_high_hz",
        "integration_ms",
        "refractory_ms",
        "match_tolerance_ms",
        "threshold_fraction",
        "threshold_window_s",
    ):
        lines.append(f"| {key} | {rp[key]} |")
    lines.append("")
    lines.append(
        "All of these are design parameters of this prototype (configs/params.yaml),")
    lines.append("not values taken from a clinical source.")
    lines.append("")
    lines.append("## Results")
    lines.append("")
    lines.append(
        "| record | fs (Hz) | duration (s) | beats annotated | peaks detected | TP | FP | FN | sensitivity | PPV |")
    lines.append(
        "|--------|---------|--------------|-----------------|----------------|----|----|----|-------------|-----|")
    for r in results:
        m = r["match"]
        lines.append(
            "| {rec} | {fs} | {dur:.1f} | {nb} | {nd} | {tp} | {fp} | {fn} | {sens} | {ppv} |".format(
                rec=r["record"],
                fs=r["fs"],
                dur=r["duration_s"],
                nb=r["n_reference"],
                nd=r["n_detected"],
                tp=m.tp,
                fp=m.fp,
                fn=m.fn,
                sens=fmt(m.sensitivity),
                ppv=fmt(m.ppv),
            )
        )
    lines.append("")
    lines.append("## Annotation symbols present (reference beats)")
    lines.append("")
    for r in results:
        lines.append(f"### Record {r['record']}")
        lines.append("")
        for symbol, count in sorted(r["symbols"].items(), key=lambda kv: (-kv[1], kv[0])):
            description = DESCRIPTIONS.get(
                symbol, "(no description in wfdb ann_label_table)")
            lines.append(f"- `{symbol}` x{count}: {description}")
        lines.append("")
    lines.append("## Limitations")
    lines.append("")
    lines.append(
        "- Terrestrial ambulatory recordings (MIT-BIH); no astronaut data was used.")
    lines.append(
        "- Record 201/202 are the same subject; per-record numbers are not independent.")
    lines.append(
        "- The reference labels are human annotations, so both misses and extra detections")
    lines.append("  include annotation decisions, not only detector errors.")
    lines.append(
        "- Records 201/202 contain rhythm changes and noisy stretches; the numbers are")
    lines.append("  reported as they are, however poor.")
    lines.append("- No clinical claim is made from these numbers.")
    lines.append("")
    Path(path).write_text("\n".join(lines), encoding="utf-8")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--raw-dir", default=str(ROOT / "data" / "raw" / "mitdb"))
    parser.add_argument("--records", nargs="+", default=DEFAULT_RECORDS)
    parser.add_argument("--channel", default="MLII")
    parser.add_argument("--out", default=str(ROOT / "docs" / "rpeak_eval.md"))
    args = parser.parse_args(argv)

    params = load_params()
    if not (Path(args.raw_dir) / f"{args.records[0]}.hea").exists():
        print(f"SKIP: no data in {args.raw_dir}")
        return 0

    results = []
    for record in args.records:
        result = evaluate(record, args.raw_dir, args.channel, params)
        results.append(result)
        m = result["match"]
        print(
            f"{record}: detected {result['n_detected']} / annotated {result['n_reference']} "
            f"TP {m.tp} FP {m.fp} FN {m.fn} "
            f"sensitivity {fmt(m.sensitivity)} ppv {fmt(m.ppv)}"
        )
        print("  symbols:", dict(result["symbols"]))
        for symbol, count in sorted(result["symbols"].items(), key=lambda kv: (-kv[1], kv[0])):
            print(f"    {symbol} x{count}: {DESCRIPTIONS.get(symbol, '')}")

    write_report(results, params, args.out)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
