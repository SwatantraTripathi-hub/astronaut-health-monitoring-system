#!/usr/bin/env python
"""Run the exploratory ECG-vs-monitor HR cross-check on local BIDMC records.

Writes docs/crosscheck.md. Run from the project root:

    python scripts/crosscheck_bidmc.py
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src.config import load_params
from src.features.crosscheck import crosscheck_all

CAVEAT = "one record, ICU patient, exploratory, plausibility check not accuracy validation"
HEADER = (
    "EXPLORATORY. One record, ICU patient, exploratory, plausibility check not "
    "accuracy validation. No clinical claim."
)


def write_report(results, params, path):
    lines = ["# ECG vs monitor HR cross-check", ""]
    lines.append(HEADER)
    lines.append("")
    lines.append("Generated by `scripts/crosscheck_bidmc.py`.")
    lines.append("")
    lines.append(
        "Method: detect R-peaks on BIDMC ECG lead II (125 Hz), compute HR in each "
        f"{params['crosscheck']['window_s']} s window as 60 / mean RR, and compare with the "
        "mean of the monitor's 1 Hz HR numerics over the same window (NaN samples are "
        "missing and are never averaged in as zeros)."
    )
    lines.append("")
    lines.append(
        "Only windows fully inside both recordings are used: the waveform is 60001 "
        "samples at 125 Hz (480.008 s) and the numerics are 481 samples at 1 Hz, so the "
        "last usable window ends at or before 480 s."
    )
    lines.append("")
    lines.append(
        f"A window also needs at least two detected beats and at least "
        f"{params['numerics']['min_valid_fraction']:.0%} non-missing monitor HR samples "
        "(both design parameters, no clinical source)."
    )
    lines.append("")
    lines.append("## Results")
    lines.append("")
    lines.append("| record | status | median absolute difference (bpm) | windows compared | windows skipped |")
    lines.append("|--------|--------|----------------------------------|------------------|-----------------|")
    for name, result in results.items():
        mae = "n/a" if result.median_abs_diff_bpm is None else f"{result.median_abs_diff_bpm:.2f}"
        lines.append(
            f"| {name} | {result.status} | {mae} | {result.n_compared} | {result.n_skipped} |"
        )
    lines.append("")
    lines.append("## Skipped windows and why")
    lines.append("")
    if all(not r.skipped_reasons for r in results.values()):
        lines.append("No windows were skipped.")
    else:
        for name, result in results.items():
            if not result.skipped_reasons:
                continue
            lines.append(f"### {name}")
            lines.append("")
            for reason, count in result.skipped_reasons.items():
                lines.append(f"- {reason}: {count}")
            lines.append("")
    lines.append("## Limitations")
    lines.append("")
    lines.append(f"- This is {CAVEAT}.")
    lines.append("- The monitor HR numerics and the ECG are two different sources; a difference")
    lines.append("  is not an error of either one by itself.")
    lines.append("- BIDMC is terrestrial ICU data, not astronaut data.")
    lines.append("- Only records present locally are reported; run `python scripts/download_more.py`")
    lines.append("  to add bidmc02-bidmc05.")
    lines.append("")
    Path(path).write_text("\n".join(lines), encoding="utf-8")


def main():
    params = load_params()
    results = crosscheck_all(ROOT / "data" / "raw" / "bidmc", params)
    if not results:
        print("SKIP: no local BIDMC record pairs found")
        return 0
    for name, result in results.items():
        mae = "n/a" if result.median_abs_diff_bpm is None else f"{result.median_abs_diff_bpm:.2f}"
        print(
            f"{name}: {result.status}, median abs diff {mae} bpm, "
            f"compared {result.n_compared}, skipped {result.n_skipped}"
        )
        for reason, count in result.skipped_reasons.items():
            print(f"  skipped {count}: {reason}")
    write_report(results, params, ROOT / "docs" / "crosscheck.md")
    print("wrote docs/crosscheck.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
